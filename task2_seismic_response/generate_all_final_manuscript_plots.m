% 5. Appendix A median detected-transition time and PGA heatmaps.
plot_grid_median_failure_time_7x10(FT_file, ...
    'FailureMode','response','TimeUnit','s','Points',1:10,'Responses',1:7, ...
    'ResponseLabels',labels,'ShowValues',true,'ValueFormat','%.2f', ...
    'ShowFailedPct',true,'PctFormat','%.0f%%','TextMode','both', ...
    'Colormap','hot','RobustLimits',true,'CLimPctl',[5 95], ...
    'SaveDir',outDir,'FileTag','','ExportDPI',300, ...
    'FigPosition',[60 60 4200 2800],'FontName','Arial','FontSize',26, ...
    'CellFontSize',12,'TopLabelFontSize',26,'SideLabelFontSize',26, ...
    'AxesPosition',[0.060 0.055 0.82 0.89]);
