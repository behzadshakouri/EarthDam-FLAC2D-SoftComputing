    'FailureMode','response','FigMode','all_in_one','MinFailed',10, ...
    'XLabel','PGA at detected transition','SaveDir',outDir, ...
    'ExportDPI',300,'FigPosition',[60 60 4200 2800], ...
    'FontName','Arial','FontSize',18,'LabelFontSize',22);
