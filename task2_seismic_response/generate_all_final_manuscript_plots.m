    'Silent',true,'CloseFigures',true);

expected={ ...
 'CDF_PGAfail_GRID70_mode_response.png'; ...
 'ALL70_failure_summary_mode_response_color_t_median.png'; ...
 'ALL70_SAFE_obs_vs_pred_ELMIGWO.png';'COMPARE_dashboard.png'; ...
 'COMPARE_wins_top2.png'; ...
 'ALL70_median_failure_time_mode_response_unit_s.png'; ...
 'ALL70_median_failure_PGA_response.png'; ...
 'CDF_PGAfail_ALL70_mode_response.png'; ...
 'ALL70_SAFE_obs_vs_pred_ELM.png'; ...
 'ALL70_SAFE_obs_vs_pred_ELMABC.png'; ...
 'ALL70_SAFE_obs_vs_pred_ELMACOR.png'};
exists=cellfun(@(n)isfile(fullfile(outDir,n)),expected);
manifest=table(string(expected),exists, ...
    'VariableNames',{'manuscript_file','generated'});
writetable(manifest,fullfile(outDir,'final_manuscript_figure_manifest.csv'));
if ~all(exists)
    warning('Task2:IncompleteFigureSet','Some manuscript result figures were not generated.');
end
disp(manifest);
fprintf('All final result figures were written to:\n%s\n',outDir);
end

function path=find_project_file(root,pattern)
% Search the Task 2 package and nearby project Data/results folders.
% The user's normal layout places Data beside Revision_codes.
bases={root}; current=root;
for i=1:4
    current=fileparts(current);
    if isempty(current),break;end
    bases{end+1}=current; %#ok<AGROW>
end
candidates={};
for i=1:numel(bases)
    candidates=[candidates, {bases{i},fullfile(bases{i},'data'), ...
        fullfile(bases{i},'Data'),fullfile(bases{i},'results')}]; %#ok<AGROW>
end
path=''; newest=-inf;
for i=1:numel(candidates)
    if ~isfolder(candidates{i}),continue;end
    d=dir(fullfile(candidates{i},'**',pattern));
    if isempty(d),continue;end
    [stamp,k]=max([d.datenum]);
    if stamp>newest
        newest=stamp; path=fullfile(d(k).folder,d(k).name);
    end
end
if isempty(path)
    warning('Task2:ProjectFileNotFound', ...
        'Could not locate %s below the Task 2 package or nearby Data/results folders.',pattern);
else
    fprintf('Using %s\n  %s\n',pattern,path);
end
end
