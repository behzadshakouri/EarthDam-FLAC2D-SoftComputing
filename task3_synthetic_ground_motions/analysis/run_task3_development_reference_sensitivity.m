function summary=run_task3_development_reference_sensitivity()
%RUN_TASK3_DEVELOPMENT_REFERENCE_SENSITIVITY Audit split-fitted QC references.
% The numerical-runaway reference maximum is recomputed from the 105
% development records in each accepted split and then applied to all 150
% records. This is a robustness audit, not a supervised failure model.

analysisDir=fileparts(mfilename('fullpath')); root=fileparts(analysisDir);
addpath(root); setup_task3; cfg=task3_config(root);
prepared=load(fullfile(cfg.results_dir,'task3_prepared_dataset.mat'),'dataset','qc');
raw=load(cfg.raw.task3_data_file,'Task3');
assignments=readtable(fullfile(root,'reference_results', ...
    'compact_pointwise_fmrvr_split_assignments.csv'));

[Yarchive,auditArchive,screenArchive]=build_task3_screened_targets( ...
    raw.Task3,prepared.dataset,prepared.qc,cfg,5);
rows=table;
for repeat=1:10
    split=assignments(assignments.repeat==repeat,:);
    development=split.realization_id(split.partition=="development");
    [Ydev,auditDev,screenDev]=build_task3_screened_targets( ...
        raw.Task3,prepared.dataset,prepared.qc,cfg,5,development);
    affected=auditArchive.had_sentinel;
    onsetDifference=abs(auditDev.screening_onset_s(affected)- ...
        auditArchive.screening_onset_s(affected));
    targetScale=max(abs(Yarchive),1e-12);
    targetDifference=abs(Ydev-Yarchive)./targetScale;
    ratio=screenDev.reference_maximum./max(screenArchive.reference_maximum,eps);
    rows=[rows;table(repeat,numel(development), ...
        sum(isfinite(auditDev.screening_onset_s)), ...
        sum(auditDev.screening_onset_s==auditArchive.screening_onset_s), ...
        median(onsetDifference),max(onsetDifference), ...
        percentile(targetDifference(:),95),max(targetDifference(:)), ...
        min(ratio),max(ratio), ...
        'VariableNames',{'repeat','development_records','screened_records', ...
        'identical_onset_records','median_onset_difference_s', ...
        'maximum_onset_difference_s','p95_relative_target_change', ...
        'maximum_relative_target_change','minimum_reference_ratio', ...
        'maximum_reference_ratio'})]; %#ok<AGROW>
    fprintf('Development-reference screening audit %d/10 complete.\n',repeat);
end

out=task3_analysis_results_root(root); if ~exist(out,'dir'),mkdir(out);end
writetable(rows,fullfile(out,'development_reference_screening_by_split.csv'));
writetable(rows,fullfile(root,'reference_results', ...
    'development_reference_screening_by_split.csv'));
summary=table(mean(rows.screened_records),min(rows.identical_onset_records), ...
    median(rows.median_onset_difference_s),max(rows.maximum_onset_difference_s), ...
    mean(rows.p95_relative_target_change),max(rows.maximum_relative_target_change), ...
    min(rows.minimum_reference_ratio),max(rows.maximum_reference_ratio), ...
    'VariableNames',{'mean_screened_records','minimum_identical_onset_records', ...
    'median_of_median_onset_difference_s','maximum_onset_difference_s', ...
    'mean_p95_relative_target_change','maximum_relative_target_change', ...
    'minimum_reference_ratio','maximum_reference_ratio'});
writetable(summary,fullfile(out,'development_reference_screening_summary.csv'));
writetable(summary,fullfile(root,'reference_results', ...
    'development_reference_screening_summary.csv'));
disp(summary);
end

function value=percentile(x,p)
x=sort(x(isfinite(x))); if isempty(x),value=NaN;return;end
position=1+(numel(x)-1)*p/100; lower=floor(position); upper=ceil(position);
if lower==upper,value=x(lower);else,value=x(lower)+(position-lower)*(x(upper)-x(lower));end
end
